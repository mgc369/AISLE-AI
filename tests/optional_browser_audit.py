"""Optional real Chromium UI audit (requires Playwright and Chromium).

Runs the real frontend in a browser with mock response payloads generated by
the real Python engine. The HTTP server is separately verified by unittest.
"""
import asyncio, json, os, sys, re
from pathlib import Path
from playwright.async_api import async_playwright
D=Path(__file__).resolve().parents[1] / 'web'
sys.path.insert(0,str(D.parent))
from engine.algorithms import analyze_mission
from engine.scenarios import scenarios
presets=scenarios()
results={k:analyze_mission(v,trials=5) for k,v in presets.items()}
# browser mocked API only, the real endpoints are tested independently
inline_fetch="""<script>
const PRESETS = __PRESETS__;
const RESULTS = __RESULTS__;
window.fetch = async (url,opts) => {
  if(url==='/api/presets') return {ok:true, json:async()=>({presets:PRESETS})};
  let mission=JSON.parse(opts.body);
  let k=Object.keys(PRESETS).find(key=>PRESETS[key].name===mission.name) || 'standard';
  await new Promise(resolve=>setTimeout(resolve,k==='disruption'?500:15));
  let data=JSON.parse(JSON.stringify(RESULTS[k]));
  if(window.__zeroBaseline) {data.mdp.shortest_controller.mean_hazard_entries=0;data.mdp.risk_aware_controller.mean_hazard_entries=2;}
  return {ok:true,json:async()=>data};
};</script>""".replace('__PRESETS__',json.dumps(presets)).replace('__RESULTS__',json.dumps(results))
html=re.sub(r'<link rel="stylesheet" href="/styles\.css(?:\?[^"]*)?" />', lambda _: '<style>'+(D/'styles.css').read_text(encoding='utf-8')+'</style>', (D/'index.html').read_text(encoding='utf-8'))
html=html.replace('<script src="/app.js"></script>',inline_fetch+'<script>'+(D/'app.js').read_text(encoding='utf-8')+'</script>')
async def main():
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_PATH') or ('/usr/bin/chromium' if Path('/usr/bin/chromium').exists() else None),args=['--no-sandbox'])
  for width,height in [(1440,900),(390,844),(320,700)]:
   page=await browser.new_page(viewport={'width':width,'height':height})
   errors=[]; page.on('pageerror',lambda e: errors.append(str(e)))
   await page.set_content(html,wait_until='load')
   await page.wait_for_function("document.querySelector('#missionStatus').textContent==='MISSION PLANNED'")
   assert await page.locator('#baseSteps').inner_text()=='70'
   assert await page.locator('#optSteps').inner_text()=='62'
   dimensions=await page.evaluate('''() => [document.documentElement.scrollWidth,window.innerWidth]''')
   assert dimensions[0]<=dimensions[1], dimensions
   # A decorative icon must never expand a selector into a tall empty panel.
   for selector in ['#presetSelect', '#viewSelect']:
    geometry=await page.locator(selector).evaluate('''el => {
      const control=el.getBoundingClientRect(), wrapper=el.parentElement.getBoundingClientRect();
      return {height:control.height, wrapper:wrapper.height, offset:control.top-wrapper.top};
    }''')
    assert 40<=geometry['height']<=48, geometry
    assert geometry['wrapper']<=48 and abs(geometry['offset'])<1, geometry
   await page.locator('#viewSelect').select_option('nearest')
   await page.locator('#forwardBtn').click()
   assert (await page.locator('#timeStamp').inner_text()).startswith('001 /')
   await page.locator('#policyBtn').click()
   assert await page.locator('#viewSelect').input_value()=='mdp'
   assert await page.locator('#policyBtn').get_attribute('aria-pressed')=='true'
   await page.locator('button[data-tool="hazard"]').click()
   await page.locator('#warehouseCanvas').scroll_into_view_if_needed()
   box=await page.locator('#warehouseCanvas').bounding_box()
   await page.mouse.click(box['x']+box['width']*0.15,box['y']+box['height']*0.25)
   assert await page.locator('#missionStatus').inner_text()=='REPLAN REQUIRED'
   assert await page.locator('#policyBtn').get_attribute('aria-pressed')=='false'
   # Quick switching during expensive requests must NOT insert previous results
   await page.locator('#presetSelect').select_option('disruption')
   await page.wait_for_timeout(50)
   await page.locator('#presetSelect').select_option('narrow')
   await page.wait_for_function("document.querySelector('#missionStatus').textContent==='MISSION PLANNED' && document.querySelector('#baseSteps').textContent==='60'",timeout=5000)
   await page.wait_for_timeout(600)
   assert await page.locator('#baseSteps').inner_text()=='60', 'Stale previous response overwrote current mission'
   assert await page.locator('#missionStatus').inner_text()=='MISSION PLANNED'
   # If baseline is zero, cannot compute a percentage reduction with positive MDP exposure
   await page.evaluate('window.__zeroBaseline = true')
   await page.locator('#runBtn').click()
   await page.wait_for_function("document.querySelector('#riskReduction').textContent==='N/A'",timeout=5000)
   assert 'undefined' in await page.locator('#riskReductionLabel').inner_text()
   assert not errors,errors
   if os.environ.get('AISLE_AUDIT_SCREENSHOTS'):
    await page.screenshot(path=str(D.parent/f'browser-audit-{width}.png'),full_page=True)
   print(f'Browser QA {width}x{height}: PASS (UI actions, editing, policy, race, metric edge case, {dimensions})')
   await page.close()
  await browser.close()
asyncio.run(main())
